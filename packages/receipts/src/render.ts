import type { Receipt } from "./types.ts";

/** Escape a value for a Markdown table cell. */
export function escapeCell(value: string): string {
  return value.replaceAll("|", "\\|").replaceAll("\n", " ").trim();
}

/** Truncate a string without splitting a surrogate pair. */
export function truncate(value: string, limit = 80): string {
  const characters = [...value];
  if (characters.length <= limit) return value;
  return `${characters.slice(0, Math.max(0, limit - 1)).join("")}…`;
}

export interface PrBatchRow {
  id: string;
  symbols: number;
  files: number;
  lines: number;
  outcome: string;
  checks: string;
}

export interface PrContext {
  planId: string;
  branch: string;
  baseRef: string;
  headCommit: string;
  orphanDelta: number;
  batches: PrBatchRow[];
  rejected: Array<{ symbols: string[]; check: string; reason: string }>;
  receipts: Receipt[];
}

function statusIcon(outcome: string): string {
  if (outcome === "verified") return "verified";
  if (outcome === "flaky") return "verified (flaky)";
  return outcome;
}

/** Render the PR body. Deterministic for the same plan and receipts. */
export function renderPrBody(context: PrContext): string {
  const verified = context.receipts.filter((receipt) => receipt.outcome === "verified" || receipt.outcome === "flaky").length;
  const rejected = context.receipts.filter((receipt) => receipt.outcome !== "verified" && receipt.outcome !== "flaky").length;
  const lines: string[] = [
    "## Shrike verified cleanup",
    "",
    `Plan \`${context.planId}\` on \`${context.branch}\`.`,
    "",
    `- Base: \`${context.baseRef}\``,
    `- Head: \`${context.headCommit}\``,
    `- Orphan-delta findings: **${context.orphanDelta}**`,
    `- Batches: **${context.batches.length}** (${verified} verified, ${rejected} rejected)`,
    "",
    "| Batch | Outcome | Symbols | Files | Lines | Checks |",
    "|---|---|---:|---:|---:|---|",
  ];
  for (const batch of context.batches) {
    lines.push(`| ${escapeCell(batch.id)} | ${statusIcon(batch.outcome)} | ${batch.symbols} | ${batch.files} | ${batch.lines} | ${escapeCell(truncate(batch.checks, 60))} |`);
  }
  if (context.rejected.length > 0) {
    lines.push("", "### Rejected deletions", "", "| Symbols | Check | Reason |", "|---|---|---|");
    for (const item of context.rejected) {
      lines.push(`| ${escapeCell(truncate(item.symbols.join(", "), 100))} | ${escapeCell(item.check)} | ${escapeCell(truncate(item.reason, 120))} |`);
    }
  }
  lines.push("", "### Receipts", "");
  for (const receipt of context.receipts) {
    lines.push(`- \`${receipt.id}\` — ${receipt.outcome} — \`${receipt.contentHash}\``);
  }
  lines.push(
    "",
    "Every verified batch was applied in isolation and checked against a baseline.",
    "Rejected batches were reverted; the tree was never left half-applied.",
    "",
    "_Generated by Shrike. Review the diff before merging._",
  );
  return `${lines.join("\n")}\n`;
}

/** Render one PR comment for a receipt. */
export function renderReceiptComment(receipt: Receipt): string {
  const lines: string[] = [
    `## Shrike receipt \`${receipt.id}\``,
    "",
    `- Outcome: **${receipt.outcome}**`,
    `- Batch: \`${receipt.batch.id}\``,
    `- Symbols: ${receipt.batch.symbols.length}`,
    `- Files: ${receipt.batch.files.length}`,
    `- Lines removed: ${receipt.batch.linesRemoved}`,
    `- Content hash: \`${receipt.contentHash}\``,
    `- Artifact: \`.shrike/receipts/${receipt.id}.json\``,
    "",
    "| Check | Status | Baseline | Classification |",
    "|---|---|---|---|",
  ];
  for (const check of receipt.checks) {
    lines.push(`| ${escapeCell(check.name)} | ${escapeCell(check.status)} | ${escapeCell(check.baselineStatus ?? "missing")} | ${escapeCell(check.classification ?? "unknown")} |`);
  }
  if (receipt.rejected.length > 0) {
    lines.push("", "### Rejected", "");
    for (const item of receipt.rejected) {
      lines.push(`- ${escapeCell(truncate(item.symbols.join(", "), 120))} — ${escapeCell(item.check ?? "unknown")} — ${escapeCell(item.reason ?? "")}`);
    }
  }
  lines.push("", "_Receipts are content-addressed; re-run the same plan to reproduce this ID._");
  return `${lines.join("\n")}\n`;
}
