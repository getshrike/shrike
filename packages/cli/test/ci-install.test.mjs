import test from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const cli = join(root, "packages", "cli", "src", "main.ts");

function scratch() {
  return mkdtempSync(join(tmpdir(), "shrike-ci-"));
}

function run(directory, args) {
  return spawnSync(process.execPath, [cli, ...args], {
    cwd: directory,
    encoding: "utf8",
    env: { ...process.env, NO_COLOR: "1" },
  });
}

function readWorkflow(directory, path = ".github/workflows/shrike.yml") {
  return readFileSync(join(directory, path), "utf8");
}

function cleanup(directory) {
  rmSync(directory, { recursive: true, force: true });
}

test("writes an advisory workflow with least permissions", () => {
  const directory = scratch();
  try {
    const result = run(directory, ["ci", "install", "--json"]);
    assert.equal(result.status, 0, result.stderr);
    const parsed = JSON.parse(result.stdout);
    assert.deepEqual(parsed, {
      path: ".github/workflows/shrike.yml",
      action: "created",
      mode: "advisory",
      base: "origin/main",
      gate: false,
    });
    const yaml = readWorkflow(directory);
    assert.match(yaml, /^# Generated by shrike ci install/m);
    assert.match(yaml, /fail-on: never/);
    assert.match(yaml, /^  contents: read$/m);
    assert.match(yaml, /fetch-depth: 0/);
    assert.match(yaml, /getshrike\/shrike\/packages\/action@v1/);
    assert.match(yaml, /mode: delta/);
    assert.match(yaml, /max-items: "0"/);
    assert.doesNotMatch(yaml, /pull-requests: write/);
    assert.doesNotMatch(yaml, /pull_request_target/);
    assert.doesNotMatch(yaml, /secrets/);
  } finally {
    cleanup(directory);
  }
});

test("--gate makes newly dead code blocking and adds the documented permission", () => {
  const directory = scratch();
  try {
    const parsed = JSON.parse(run(directory, ["ci", "install", "--gate", "--json"]).stdout);
    assert.equal(parsed.mode, "gate");
    assert.equal(parsed.gate, true);
    const yaml = readWorkflow(directory);
    assert.match(yaml, /fail-on: newly-dead/);
    assert.match(yaml, /^  contents: read$/m);
    assert.match(yaml, /^  pull-requests: write$/m);
    assert.match(yaml, /--gate makes newly dead code fail/);
  } finally {
    cleanup(directory);
  }
});

test("honors --path, --base, and --max-items", () => {
  const directory = scratch();
  try {
    const parsed = JSON.parse(run(directory, [
      "ci", "install", "--json",
      "--path", ".github/workflows/custom.yaml",
      "--base", "origin/develop",
      "--max-items", "25",
    ]).stdout);
    assert.equal(parsed.path, ".github/workflows/custom.yaml");
    assert.equal(parsed.base, "origin/develop");
    const yaml = readWorkflow(directory, ".github/workflows/custom.yaml");
    assert.match(yaml, /base: origin\/develop/);
    assert.match(yaml, /max-items: "25"/);
  } finally {
    cleanup(directory);
  }
});

test("an identical workflow is unchanged", () => {
  const directory = scratch();
  try {
    run(directory, ["ci", "install", "--json"]);
    const before = readWorkflow(directory);
    const parsed = JSON.parse(run(directory, ["ci", "install", "--json"]).stdout);
    assert.equal(parsed.action, "unchanged");
    assert.equal(readWorkflow(directory), before);
  } finally {
    cleanup(directory);
  }
});

test("a different unmanaged workflow is refused without --force", () => {
  const directory = scratch();
  try {
    mkdirSync(join(directory, ".github/workflows"), { recursive: true });
    writeFileSync(join(directory, ".github/workflows/shrike.yml"), "name: custom\n");
    const result = run(directory, ["ci", "install", "--json"]);
    assert.equal(result.status, 2);
    const parsed = JSON.parse(result.stdout);
    assert.equal(parsed.action, "skipped");
    assert.equal(readWorkflow(directory), "name: custom\n");
  } finally {
    cleanup(directory);
  }
});

test("--force replaces a different unmanaged workflow", () => {
  const directory = scratch();
  try {
    mkdirSync(join(directory, ".github/workflows"), { recursive: true });
    writeFileSync(join(directory, ".github/workflows/shrike.yml"), "name: custom\n");
    const parsed = JSON.parse(run(directory, ["ci", "install", "--json", "--force"]).stdout);
    assert.equal(parsed.action, "updated");
    assert.match(readWorkflow(directory), /^# Generated by shrike ci install/);
  } finally {
    cleanup(directory);
  }
});

test("a managed workflow with a different mode needs --force", () => {
  const directory = scratch();
  try {
    run(directory, ["ci", "install", "--json"]);
    const result = run(directory, ["ci", "install", "--gate", "--json"]);
    assert.equal(result.status, 2);
    assert.equal(JSON.parse(result.stdout).action, "skipped");
    const forced = run(directory, ["ci", "install", "--gate", "--json", "--force"]);
    assert.equal(forced.status, 0);
    assert.equal(JSON.parse(forced.stdout).action, "updated");
  } finally {
    cleanup(directory);
  }
});

test("rejects path traversal and absolute workflow paths", () => {
  const directory = scratch();
  try {
    for (const path of ["../evil.yml", "/tmp/evil.yml", ".github/workflows/../../evil.yml", ".github/evil.yml", ".github/workflows/evil.txt"]) {
      const result = run(directory, ["ci", "install", "--json", "--path", path]);
      assert.equal(result.status, 2, path);
      assert.match(result.stderr, /workflow path/, path);
    }
    assert.ok(!existsSync(join(directory, ".github")));
  } finally {
    cleanup(directory);
  }
});

test("--dry-run prints the YAML and writes nothing", () => {
  const directory = scratch();
  try {
    const result = run(directory, ["ci", "install", "--dry-run"]);
    assert.equal(result.status, 0, result.stderr);
    assert.match(result.stdout, /dry run/);
    assert.match(result.stdout, /fail-on: never/);
    assert.match(result.stdout, /\.github\/workflows\/shrike\.yml/);
    assert.ok(!existsSync(join(directory, ".github")));
  } finally {
    cleanup(directory);
  }
});

test("a symlinked workflows directory that escapes the repository is refused", () => {
  const directory = scratch();
  const outside = mkdtempSync(join(tmpdir(), "shrike-ci-outside-"));
  try {
    mkdirSync(join(directory, ".github"), { recursive: true });
    symlinkSync(outside, join(directory, ".github/workflows"));
    const result = run(directory, ["ci", "install", "--json"]);
    assert.notEqual(result.status, 0);
    assert.deepEqual(readdirSync(outside), []);
  } finally {
    cleanup(directory);
    cleanup(outside);
  }
});
