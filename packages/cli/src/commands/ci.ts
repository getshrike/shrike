import { booleanFlag, hasFlag, rejectUnknownFlags, stringFlag, type ParsedArgs } from "../args.ts";
import { ExitCode, UsageError } from "../errors.ts";
import { writeHuman, writeJson } from "../output.ts";
import {
  readInstallFile,
  validateWorkflowPath,
  writeInstallFile,
} from "../install/files.ts";

const CI_FLAGS = [
  "json",
  "help",
  "gate",
  "force",
  "dry-run",
  "path",
  "base",
  "max-items",
];

const DEFAULT_PATH = ".github/workflows/shrike.yml";
const DEFAULT_BASE = "origin/main";
const DEFAULT_MAX_ITEMS = 0;
const MARKER = "# Generated by shrike ci install";

export interface WorkflowOptions {
  path: string;
  base: string;
  gate: boolean;
  maxItems: number;
}

function yamlScalar(value: string): string {
  if (/^[A-Za-z0-9._/@+-]+$/.test(value)) return value;
  return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

export function generateWorkflow(options: WorkflowOptions): string {
  const mode = options.gate ? "gate" : "advisory";
  const permission = options.gate
    ? "  contents: read\n  pull-requests: write"
    : "  contents: read";
  const gateComment = options.gate
    ? "# --gate makes newly dead code fail the check. pull-requests: write is\n# needed only for the advisory PR comment.\n"
    : "# Advisory by default: report dead weight and newly dead code without\n# failing the pull request. Use --gate to make newly dead code blocking.\n";
  return `${MARKER}
${gateComment}name: shrike

on:
  pull_request:

permissions:
${permission}

jobs:
  shrike:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - uses: getshrike/shrike/packages/action@v1
        with:
          mode: delta
          base: ${yamlScalar(options.base)}
          fail-on: ${options.gate ? "newly-dead" : "never"}
          max-items: "${options.maxItems}"
`;
}

function validateBase(base: string): string {
  if (base.length === 0) throw new UsageError("--base requires a non-empty ref");
  if (/[\s#]/.test(base)) throw new UsageError(`invalid --base ref: ${base}`);
  return base;
}

function maxItems(args: ParsedArgs): number {
  const raw = stringFlag(args, "max-items");
  if (raw === undefined) {
    if (hasFlag(args, "max-items")) throw new UsageError("--max-items requires a number");
    return DEFAULT_MAX_ITEMS;
  }
  if (!/^\d+$/.test(raw)) throw new UsageError(`invalid --max-items value: ${raw}`);
  return Number.parseInt(raw, 10);
}

interface CiResult {
  path: string;
  action: "created" | "updated" | "unchanged" | "skipped";
  mode: "advisory" | "gate";
  base: string;
  gate: boolean;
  dryRun?: true;
}

export async function ciInstallCommand(root: string, args: ParsedArgs): Promise<number> {
  rejectUnknownFlags(args, CI_FLAGS);
  if (args.positionals.length > 0) {
    throw new UsageError(`unexpected argument: ${args.positionals[0]}`);
  }
  const rawPath = stringFlag(args, "path") ?? DEFAULT_PATH;
  if (hasFlag(args, "path") && stringFlag(args, "path") === undefined) {
    throw new UsageError("--path requires a value");
  }
  let path: string;
  try {
    path = validateWorkflowPath(rawPath);
  } catch (error) {
    throw new UsageError(error instanceof Error ? error.message : String(error));
  }
  const base = validateBase(stringFlag(args, "base") ?? DEFAULT_BASE);
  const gate = booleanFlag(args, "gate");
  const force = booleanFlag(args, "force");
  const dryRun = booleanFlag(args, "dry-run");
  const options: WorkflowOptions = { path, base, gate, maxItems: maxItems(args) };
  const content = generateWorkflow(options);

  let existing: string | null = null;
  try {
    existing = readInstallFile(root, path);
  } catch (error) {
    throw new UsageError(error instanceof Error ? error.message : String(error));
  }

  let action: CiResult["action"];
  if (existing === null) {
    action = "created";
  } else if (existing === content) {
    action = "unchanged";
  } else if (force) {
    action = "updated";
  } else {
    action = "skipped";
  }

  if (!dryRun && (action === "created" || action === "updated")) {
    try {
      writeInstallFile(root, path, content);
    } catch (error) {
      throw new UsageError(error instanceof Error ? error.message : String(error));
    }
  }

  const result: CiResult = {
    path,
    action,
    mode: gate ? "gate" : "advisory",
    base,
    gate,
    ...(dryRun ? { dryRun: true as const } : {}),
  };

  if (booleanFlag(args, "json")) {
    writeJson(result);
  } else if (dryRun) {
    writeHuman(`Shrike CI install (dry run: no files written)`);
    writeHuman(`  path    ${path}`);
    writeHuman(`  mode    ${result.mode}${gate ? " (fail-on: newly-dead)" : " (fail-on: never)"}`);
    writeHuman(`  base    ${base}`);
    writeHuman("");
    writeHuman(content.trimEnd());
  } else if (action === "skipped") {
    writeHuman(`Shrike CI install`);
    writeHuman(`  skipped ${path} (existing workflow is not managed by shrike; rerun with --force)`);
    writeHuman("  No files were changed.");
  } else {
    writeHuman(`Shrike CI install`);
    writeHuman(`  ${action.padEnd(9)} ${path}`);
    writeHuman(`  mode    ${result.mode}${gate ? " (fail-on: newly-dead)" : " (fail-on: never)"}`);
    writeHuman(`  base    ${base}`);
    writeHuman("");
    writeHuman("Next: commit the workflow and open a PR.");
  }

  if (action === "skipped" && !dryRun) return ExitCode.USAGE;
  return ExitCode.OK;
}

export async function ciCommand(root: string, args: ParsedArgs): Promise<number> {
  const action = args.positionals[0];
  if (action !== "install") {
    throw new UsageError("usage: shrike ci install [--gate] [--dry-run] [--force] [--json]");
  }
  const rest: ParsedArgs = {
    positionals: args.positionals.slice(1),
    values: args.values,
    ...(args.repeated ? { repeated: args.repeated } : {}),
  };
  return ciInstallCommand(root, rest);
}
